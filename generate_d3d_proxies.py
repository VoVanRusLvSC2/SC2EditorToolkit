"""Generate typed, synchronous thread dispatch from the installed SDK ABI."""
import re
from pathlib import Path
root=Path(__file__).resolve().parent
header=Path(r'C:\Program Files (x86)\Windows Kits\10\Include\10.0.26100.0\shared\d3d9.h').read_text()
interfaces={}
for name,body in re.findall(r'DECLARE_INTERFACE_\((\w+),\s*\w+\)\s*\{(.*?)\n\};',header,re.S):
    if name in ('IDirect3D9ExOverlayExtension','IDirect3DDevice9Video','IDirect3DAuthenticatedChannel9','IDirect3DCryptoSession9'): continue
    methods=[]
    for ret,name2,name3,args in re.findall(r'STDMETHOD(?:_\(([^,]+),\s*(\w+)\)|\((\w+)\))\((.*?)\)\s*PURE;',body,re.S):
        args=re.sub(r'^THIS_?\s*','',args.strip())
        params=[]
        for a in args.split(',') if args else []:
            a=' '.join(a.split())
            m=re.fullmatch(r'(.*?)\b(\w+)(\[.*?\])?',a)
            if not m:typ,var,array=a,'unnamed'+str(len(params)),None
            else:
                typ,var,array=m.groups()
                if not typ.strip():typ,var=a,'unnamed'+str(len(params))
            typ=typ.strip()+(' *' if array else '')
            params.append((typ,var))
        methods.append((ret.strip() or 'HRESULT',name2 or name3,params))
    interfaces[name]=methods
custom={'QueryInterface','AddRef','Release','CreateDevice','CreateDeviceEx','Reset','ResetEx','Present','PresentEx','GetCreationParameters','CreateAdditionalSwapChain'}
lines=['// Generated by generate_d3d_proxies.py. Do not edit by hand.']
for name in interfaces:lines.append(f'static void Wrap_{name}({name}* value);')
for interface,methods in interfaces.items():
    for slot,(ret,name,params) in enumerate(methods):
        if name in custom:continue
        decl=', '.join(t+' '+v for t,v in params)
        types=''.join(', '+t for t,v in params)
        args=''.join(', '+v for t,v in params)
        lines.append(f'static {ret} STDMETHODCALLTYPE P_{interface}_{name}(void* bridgeSelf'+(', '+decl if decl else '')+') {')
        lines.append(f'  Trace(L"{interface}::{name}");')
        lines.append(f'  auto bridgeFn=Original<{ret}(STDMETHODCALLTYPE*)(void*{types})>(bridgeSelf,{slot});')
        if ret!='void':lines.append(f'  {ret} bridgeResult{{}};')
        lines.append('  Invoke([&]{'+('bridgeResult=' if ret!='void' else '')+f'bridgeFn(bridgeSelf{args});'+'});')
        # The one interface** input in this ABI is CheckResourceResidency.
        if name!='CheckResourceResidency':
            for typ,var in params:
                m=re.fullmatch(r'(IDirect3D\w+)\s*\*\s*\*',typ)
                if m and m[1] in interfaces:
                    cond='SUCCEEDED(bridgeResult)&&' if ret=='HRESULT' else ''
                    lines.append(f'  if({cond}{var}&&*{var})Wrap_{m[1]}(*{var});')
        if ret!='void':lines.append('  return bridgeResult;')
        lines.append('}')
for interface,methods in interfaces.items():
    lines.append(f'static void Fill_{interface}(void** table) {{')
    for slot,(ret,name,params) in enumerate(methods):
        if name not in custom:lines.append(f'  table[{slot}]=reinterpret_cast<void*>(P_{interface}_{name});')
    lines.append('}')
    if interface not in ('IDirect3D9','IDirect3D9Ex','IDirect3DDevice9','IDirect3DDevice9Ex','IDirect3DBaseTexture9','IDirect3DResource9'):
        lines.append(f'static void Wrap_{interface}({interface}* value) {{auto table=Clone(value,{len(methods)},nullptr,false);if(!table)return;Fill_{interface}(table);')
        if interface.startswith('IDirect3DSwapChain9'):
            lines.append('table[3]=reinterpret_cast<void*>(SwapPresent);')
        lines.append('InterlockedExchangePointer(reinterpret_cast<void* volatile*>(value),table);}')
(root/'src'/'d3d_proxies.inc').write_text('\n'.join(lines)+'\n')
print({k:len(v) for k,v in interfaces.items()})
