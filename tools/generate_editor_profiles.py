"""Generate matching Python/native identities from the public build manifest."""
import argparse
import json
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def outputs():
    value=json.loads((ROOT/'profiles/editor_builds.json').read_text(encoding='utf8'))
    assert value['schemaVersion']==1
    rows=value['profiles'];seen=set()
    for row in rows:
        row['sha256']=row['sha256'].lower()
        assert re.fullmatch('[a-f0-9]{64}',row['sha256']) and row['sha256'] not in seen
        assert re.fullmatch(r'\d+\.\d+\.\d+\.\d+',row['version'])
        assert re.fullmatch(r'[a-zA-Z0-9.-]+',row['id']) and type(row['nativeOffsets']) is bool
        seen.add(row['sha256'])
    python='"""Generated by tools/generate_editor_profiles.py; edit profiles/editor_builds.json."""\nPROFILES = '+repr(tuple(rows))+'\n'
    header='#pragma once\n// Generated by tools/generate_editor_profiles.py; do not edit.\nstruct EditorBuildProfile {const char* id;const char* version;const char* sha256;bool nativeOffsets;};\ninline constexpr EditorBuildProfile kEditorBuildProfiles[]={\n'
    header+=''.join('    {"'+r['id']+'","'+r['version']+'","'+r['sha256']+'",'+str(r['nativeOffsets']).lower()+'},\n' for r in rows)+'};\n'
    return {ROOT/'app/editor_profiles.py':python,ROOT/'src/editor_profiles.generated.h':header}

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    for path,text in outputs().items():
        if a.check:
            if not path.is_file() or path.read_text(encoding='utf8')!=text:raise SystemExit('Outdated generated profile: '+str(path))
        else:path.write_text(text,encoding='utf8',newline='\n')

if __name__=='__main__':main()
